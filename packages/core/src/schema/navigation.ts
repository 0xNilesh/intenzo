import { z } from "zod";

import { CriterionId } from "./criterion.ts";

/** A path on the app's own origin: "/cart", never "https://…" or protocol-relative "//…". */
export const SameOriginPath = z
  .string()
  .startsWith("/", { message: "must be a path on the app's own origin" })
  .refine((p) => !p.startsWith("//"), { message: "must be a path on the app's own origin" });

/**
 * How code finds an element again. Built by code from a resolved element and verified before it's
 * saved (§20.4); the model only ever picks element ids from the outline.
 */
export const Target = z.discriminatedUnion("by", [
  z.object({ by: z.literal("testId"), id: z.string().min(1) }),
  // `nth` has no default: when role+name matches several elements, only an explicit nth picks one.
  z.object({
    by: z.literal("role"),
    role: z.string().min(1),
    name: z.string(),
    nth: z.number().int().nonnegative().optional(),
  }),
  z.object({ by: z.literal("label"), text: z.string().min(1) }),
  z.object({ by: z.literal("placeholder"), text: z.string().min(1) }),
  /** Last resort, generated by code: the shortest unique CSS path. */
  z.object({ by: z.literal("css"), selector: z.string().min(1) }),
  /** A vision-fallback click (§20.5). Replayable on the same layout only, so never exported. */
  z.object({
    by: z.literal("point"),
    x: z.number().nonnegative(),
    y: z.number().nonnegative(),
    viewport: z.tuple([z.number().int().positive(), z.number().int().positive()]),
  }),
]);
export type Target = z.infer<typeof Target>;

export const WatchTarget = z.object({
  /** What the criterion calls it, e.g. "order total". */
  label: z.string().min(1),
  /** region = a landmark, form or dialog container (§20.4). */
  scope: z.enum(["element", "region"]),
  target: Target,
});
export type WatchTarget = z.infer<typeof WatchTarget>;

export const MAX_WAIT_MS = 3000;

/** One navigator action. The model chooses these; code validates and executes them (§20.2). */
export const Step = z.discriminatedUnion("op", [
  z.object({ op: z.literal("goto"), path: SameOriginPath }),
  z.object({ op: z.literal("click"), target: Target }),
  z.object({ op: z.literal("fill"), target: Target, value: z.string() }),
  z.object({ op: z.literal("select"), target: Target, option: z.string() }),
  z.object({ op: z.literal("press"), key: z.string().min(1) }),
  z.object({
    op: z.literal("scroll"),
    direction: z.enum(["up", "down"]),
    target: Target.optional(),
  }),
  z.object({ op: z.literal("wait"), ms: z.number().int().positive().max(MAX_WAIT_MS) }),
  z.object({ op: z.literal("back") }),
]);
export type Step = z.infer<typeof Step>;

/** What a step log records: navigator steps, plus the recorder's own reload probe (§21.3). */
export const LoggedStep = z.discriminatedUnion("op", [
  ...Step.options,
  z.object({ op: z.literal("reload") }),
]);
export type LoggedStep = z.infer<typeof LoggedStep>;

const usesPoint = (target: Target | undefined) => target?.by === "point";
const stepTarget = (step: Step) => ("target" in step ? step.target : undefined);

/** A replayable route to a criterion's trigger (§20.3–§20.4). */
export const SavedPath = z
  .object({
    criterionId: CriterionId,
    setup: z.array(Step),
    /** The last trigger step defines Tt. */
    trigger: z.array(Step).min(1),
    /** Always includes at least one region, auto-added around the trigger (§20.4). */
    watch: z.array(WatchTarget).min(1),
    /** False if any step or watch target is a point: replayed, but never exported as a test. */
    portable: z.boolean(),
  })
  .superRefine((path, ctx) => {
    if (!path.watch.some((w) => w.scope === "region")) {
      ctx.addIssue({
        code: "custom",
        path: ["watch"],
        message: "must include at least one region",
      });
    }
    const hasPoint =
      [...path.setup, ...path.trigger].some((s) => usesPoint(stepTarget(s))) ||
      path.watch.some((w) => usesPoint(w.target));
    if (hasPoint && path.portable) {
      ctx.addIssue({
        code: "custom",
        path: ["portable"],
        message: "a path with a point target can't be portable",
      });
    }
  });
export type SavedPath = z.infer<typeof SavedPath>;
